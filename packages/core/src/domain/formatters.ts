// ── Shared rendering helpers ────────────────────────────────────────

type DirectiveEntry = { analysis: FileAnalysis["directives"][0]; api: StrictComponentAPI };

function collectDirectives(analyses: readonly FileAnalysis[]): DirectiveEntry[] {
  const result: DirectiveEntry[] = [];
  for (const fileAnalysis of analyses) {
    for (const directive of fileAnalysis.directives || []) {
      if (!directive.metadata.selector) continue;
      result.push({ analysis: directive, api: buildStrictAPIFromAnalysis(directive) });
    }
  }
  return result;
}

function collectPipes(analyses: readonly FileAnalysis[]): FileAnalysis["pipes"] {
  const result: FileAnalysis["pipes"][number][] = [];
  for (const fileAnalysis of analyses) {
    result.push(...(fileAnalysis.pipes || []));
  }
  return result;
}

function getImportPath(componentName: string): string {
  const config = getLibraryConfig();
  if ((config.framework ?? "angular") === "react") {
    // React: root import of the (namespace) symbol — `Dialog.Root` is used
    // as `import { Dialog } from '<pkg>'` + `<Dialog.Root>`.
    const symbol = componentName.split(".")[0];
    return `import { ${symbol} } from '${config.packageName}';`;
  }
  return `import { ... } from '${config.packageName}/${componentName}';`;
}

/**
 * Binding examples are generated by the analyzer in Angular syntax
 * (`[name]="value"`, `(name)="handler($event)"`). For React libraries the
 * same information is rendered in JSX syntax instead.
 */
function frameworkizeExample(example: string): string {
  if ((getLibraryConfig().framework ?? "angular") !== "react") return example;
  return example.replace(/^\[([^\]]+)\]="(.*)"$/, "$1={$2}").replace(/^\(([^)]+)\)=".*"$/, "$1={handler}");
}

function renderInputsTable(inputs: StrictComponentAPI["availableInputs"]): string {
  if (inputs.length === 0) return `*This component has NO inputs.*\n\n`;
  let out = `| Input | Type | Required | Default | Example |\n`;
  out += `|-------|------|----------|---------|--------|\n`;
  for (const input of inputs) {
    const req = input.required ? "YES" : "no";
    const def = input.defaultValue || "-";
    out += `| \`${input.name}\` | \`${fmtType(input.type, input.typeResolved)}\` | ${req} | ${def} | \`${frameworkizeExample(input.example)}\` |\n`;
  }
  out += `\n`;
  return out;
}

function renderOutputsTable(outputs: StrictComponentAPI["availableOutputs"]): string {
  if (outputs.length === 0) return `*This component has NO outputs.*\n\n`;
  let out = `| Output | Event Type | Example |\n`;
  out += `|--------|------------|--------|\n`;
  for (const output of outputs) {
    out += `| \`${output.name}\` | \`${fmtType(output.eventType, output.eventTypeResolved)}\` | \`${frameworkizeExample(output.example)}\` |\n`;
  }
  out += `\n`;
  return out;
}

function renderDirectivesSection(
  directives: DirectiveEntry[],
  inheritanceMap?: Record<
    string,
    { baseClass?: string; inheritedInputs: readonly any[]; inheritedOutputs: readonly any[] }
  >,
): string {
  if (directives.length === 0) return "";
  let out = `## Directives\n\n`;
  for (const { analysis: dir, api } of directives) {
    out += `### ${api.selector}\n`;
    out += `**Class:** \`${api.className}\``;
    if (dir.metadata.standalone !== undefined) {
      out += ` | **Standalone:** ${dir.metadata.standalone ? "yes" : "no"}`;
    }
    out += `\n\n`;

    out += `#### Inputs (${api.availableInputs.length})\n\n`;
    out +=
      api.availableInputs.length === 0 ? `*This directive has NO inputs.*\n\n` : renderInputsTable(api.availableInputs);

    const dirInheritance = inheritanceMap?.[api.className];
    if (dirInheritance?.inheritedInputs.length) {
      out += `#### Inherited Inputs (from ${dirInheritance.baseClass || "base class"}) (${dirInheritance.inheritedInputs.length})\n\n`;
      out += `| Input | Type | Required | Description |\n|-------|------|----------|-------------|\n`;
      for (const input of dirInheritance.inheritedInputs) {
        out += `| \`${input.name}\` | \`${fmtType(input.type, input.typeResolved)}\` | ${input.required ? "YES" : ""} | ${input.description || "-"} |\n`;
      }
      out += `\n`;
    }

    out += `#### Outputs (${api.availableOutputs.length})\n\n`;
    out +=
      api.availableOutputs.length === 0
        ? `*This directive has NO outputs.*\n\n`
        : renderOutputsTable(api.availableOutputs);

    if (dirInheritance?.inheritedOutputs.length) {
      out += `#### Inherited Outputs (from ${dirInheritance.baseClass || "base class"}) (${dirInheritance.inheritedOutputs.length})\n\n`;
      out += `| Output | Event Type | Description |\n|--------|------------|-------------|\n`;
      for (const output of dirInheritance.inheritedOutputs) {
        out += `| \`${output.name}\` | \`${fmtType(output.eventType, output.eventTypeResolved)}\` | ${output.description || "-"} |\n`;
      }
      out += `\n`;
    }

    if (dir.publicMethods && dir.publicMethods.length > 0) {
      out += `#### Public Methods\n\n`;
      for (const method of dir.publicMethods) {
        const params = method.parameters
          .map((p) => `${p.name}${p.optional ? "?" : ""}: ${fmtType(p.type, p.typeResolved)}`)
          .join(", ");
        const asyncPrefix = method.isAsync ? "async " : "";
        out += `- \`${asyncPrefix}${method.name}(${params}): ${fmtType(method.returnType, method.returnTypeResolved)}\`\n`;
      }
      out += `\n`;
    }

    if (dir.dependencies && dir.dependencies.length > 0) {
      out += `#### Dependencies\n\n`;
      for (const dep of dir.dependencies) {
        const token = dep.injectionToken ? ` (${dep.injectionToken})` : "";
        out += `- \`${dep.name}: ${fmtType(dep.type, dep.typeResolved)}\`${token}\n`;
      }
      out += `\n`;
    }
  }
  return out;
}

function renderPipesSection(pipes: FileAnalysis["pipes"]): string {
  if (pipes.length === 0) return "";
  let out = `## Pipes\n\n`;
  out += `| Pipe | Class | Transform | Pure | Standalone |\n`;
  out += `|------|-------|-----------|------|------------|\n`;
  for (const pipe of pipes) {
    const params =
      pipe.transformMethod?.parameters
        .map((p) => `${p.name}${p.optional ? "?" : ""}: ${fmtType(p.type, p.typeResolved)}`)
        .join(", ") || "value: unknown";
    const returnType = fmtType(pipe.transformMethod?.returnType ?? null, pipe.transformMethod?.returnTypeResolved);
    out += `| \`${pipe.pipeName}\` | \`${pipe.className}\` | \`(${params}) → ${returnType}\` | ${pipe.pure ? "yes" : "no"} | ${
      pipe.standalone ? "yes" : "no"
    } |\n`;
  }
  out += `\n`;
  return out;
}

// ── Response helpers ──────────────────────────────────────────────

export function jsonResponse(data: unknown) {
  return { content: [{ type: "text" as const, text: JSON.stringify(data, null, 2) }] };
}

export function textResponse(text: string) {
  return { content: [{ type: "text" as const, text }] };
}

export function errorResponse(message: string) {
  return { content: [{ type: "text" as const, text: message }], isError: true as const };
}

export function requireComponent(
  componentName: string,
): { error: ReturnType<typeof errorResponse> } | { resolved: string; matchedSelector?: string } {
  const result = resolveComponentName(componentName);

  if ("resolved" in result) {
    return { resolved: result.resolved, matchedSelector: result.matchedSelector };
  }

  if ("suggestions" in result) {
    return {
      error: errorResponse(
        `Component "${componentName}" not found. Did you mean one of these?\n${result.suggestions
          .map((s) => `  - ${s}`)
          .join("\n")}\n\nUse the exact component name from the list above.`,
      ),
    };
  }

  return { error: errorResponse(result.error) };
}

